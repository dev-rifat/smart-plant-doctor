import 'dart:convert';

import 'package:flutter/services.dart';

class DiseaseAdvice {
  const DiseaseAdvice({
    required this.nameBn,
    required this.about,
    required this.check,
    required this.doNow,
    required this.seeOfficer,
  });

  factory DiseaseAdvice.fromJson(Map<String, dynamic> j) => DiseaseAdvice(
    nameBn: j['name_bn'] as String,
    about: j['about'] as String,
    check: (j['check'] as List).cast<String>(),
    doNow: (j['do_now'] as List).cast<String>(),
    seeOfficer: j['see_officer'] as String,
  );

  final String nameBn;
  final String about;
  final List<String> check;
  final List<String> doNow;
  final String seeOfficer;
}

class RiceAdvice {
  const RiceAdvice({
    required this.byLabel,
    required this.noChemicalAdvice,
    required this.isExpertReviewed,
    required this.sources,
  });

  factory RiceAdvice.fromJson(Map<String, dynamic> j) => RiceAdvice(
    byLabel: (j['classes'] as Map<String, dynamic>).map(
      (k, v) => MapEntry(k, DiseaseAdvice.fromJson(v as Map<String, dynamic>)),
    ),
    noChemicalAdvice: j['no_chemical_advice'] as String,
    isExpertReviewed: j['review_status'] == 'expert_reviewed',
    sources: (j['sources'] as List).cast<String>(),
  );

  /// Keyed by the model's English label ("Brown spot").
  final Map<String, DiseaseAdvice> byLabel;
  final String noChemicalAdvice;

  /// Shown on screen until an agriculture officer has signed the text off.
  final bool isExpertReviewed;
  final List<String> sources;

  DiseaseAdvice forLabel(String label) =>
      byLabel[label] ?? (throw StateError('No advice for "$label"'));
}

/// Advice lives in `assets/advice/` as reviewed content, not generated by
/// an AI, so what a farmer is told for a disease is fixed and checkable.
class RiceAdviceRepository {
  RiceAdviceRepository({this.asset = 'assets/advice/rice_diseases_bn.json'});

  final String asset;
  RiceAdvice? _cache;

  Future<RiceAdvice> load() async => _cache ??= RiceAdvice.fromJson(
    jsonDecode(await rootBundle.loadString(asset)) as Map<String, dynamic>,
  );
}
