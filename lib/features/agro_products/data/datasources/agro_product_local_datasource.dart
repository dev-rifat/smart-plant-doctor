/// Bundled product catalog.
///
/// Kept local (not fetched) so the list and search work offline in the
/// field; only the AI assistant needs the network. Dosages are the commonly
/// recommended label rates in Bangladesh and are shown alongside a
/// "follow the label / ask your agriculture officer" disclaimer in the UI.
/// Prices are sample retail prices (৳) for the listed pack size — update
/// them to your supplier's rates before going live.
abstract class AgroProductLocalDataSource {
  List<AgroProduct> getAllProducts();

  /// Returns null for unknown ids (e.g. an id the AI made up).
  AgroProduct? findById(String id);
}

class AgroProductLocalDataSourceImpl implements AgroProductLocalDataSource {
  const AgroProductLocalDataSourceImpl();

  @override
  List<AgroProduct> getAllProducts() => _catalog;

  @override
  AgroProduct? findById(String id) {
    for (final p in _catalog) {
      if (p.id == id) return p;
    }
    return null;
  }
